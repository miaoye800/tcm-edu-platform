def hints_for(subject: str) -> dict[str, str]:
    """取某学科的章→经表。没定就抛，不返回空 dict（空 dict 会被当"全落第一条经"）。"""

    try:
        return CHANNEL_HINTS[subject]
    except KeyError:
        raise KeyError(
            f"学科 {subject!r} 还没有章→经对应表。请在 app/meridian/hints.py 的 "
            f"CHANNEL_HINTS 里补上（每章都要有，注释写清为什么是这条经）。"
        ) from None


def missing_hints(subject: str, chapter_keys: list[str]) -> list[str]:
    """返回没有归经偏好的章 key。接入新学科时先跑这个，比事后看地图快。"""

    table = CHANNEL_HINTS.get(subject, {})
    return [k for k in chapter_keys if k not in table]


def section_hints_for(subject: str) -> dict[str, str]:
    """取某学科的**节级**归经覆盖表。没有这张表的学科返回空 dict（正常情况）。"""

    return SECTION_HINTS.get(subject, {})


def orphan_section_hints(subject: str, section_keys: list[str]) -> list[str]:
    """覆盖表里指向不存在节的条目。打错一个 key 会让整节静默落回章级经脉。"""

    table = SECTION_HINTS.get(subject, {})
    known = set(section_keys)
    return sorted(k for k in table if k not in known)


