"""文稿写作的提示词。

三条硬经验写进提示里，否则输出会退回「条目复述 + 一大段大白话」：

1. **先读整句话再动笔**。用户说「做个计划，我过四级又要学中药学」时，要的是
   两条线怎么排的取舍，不是「目标与现状 / 前置准备 / 阶段路线」这套放之四海
   皆准的五节。体裁、章节、每节的呈现形态都由 ``DOC_SPEC_SYSTEM_PROMPT``
   读出来，规则只做兜底（见 ``docs/spec.py``）。
2. **排版是内容的一部分**。旧提示只说「以自然段为主」，模型就交回整屏段落——
   读者看到的是墙上贴了一张纸。现在每节都要有「一句结论 + 结构化主体」，
   表格、步骤、清单按这一节的内容形态选，而不是凭模型心情。
3. **没有依据就不要装依据，有依据就要用上**。库里的章节名、方名、药名照用，
   引用标 ``[n]``；库外内容按通用知识写，但不许编书名页码。
"""

