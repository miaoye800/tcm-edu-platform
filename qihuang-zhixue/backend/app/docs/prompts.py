    "glossary 里挑 2-4 个。\n"
    "10. interpretation：2-4 句「我怎么理解你的要求」，给用户看。必须是纯人话，"
    "**不许出现任何字段名或英文键名**（genre、form、must_cover、organization_kind 一律不许写），"
