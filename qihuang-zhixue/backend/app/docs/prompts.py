    "   - goal：这一节要解决什么问题；\n"
    "   - must_cover：2-5 个必须出现的点（名词短语）。**用户原话里提的要求要落到某一节的这里**，"
    "落不进去就说明你漏读了他的话；\n"
    "   - form：这一节该长什么样 —— prose（2-4 个自然段）/ table（一张对照表）/ steps（编号步骤）/ "
    "checklist（待办清单）/ qa（一问一答）/ mixed。\n"
    "   **不要所有节都给 prose**：有可对照的东西给 table，有先后顺序给 steps，有要执行给 checklist。\n"
